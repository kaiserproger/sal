BEGIN;

CREATE TABLE warehouses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (octet_length(name) BETWEEN 1 AND 256),
    available boolean NOT NULL DEFAULT true
);

CREATE TABLE items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (octet_length(name) BETWEEN 1 AND 256),
    size text NOT NULL CHECK (octet_length(size) BETWEEN 1 AND 64),
    code text NOT NULL UNIQUE CHECK (octet_length(code) BETWEEN 1 AND 128)
);

-- A code identifies an item globally; quantities and reservations are per warehouse.
-- Keep total stock intact when reserving, and derive remaining as quantity - reserved.
CREATE TABLE inventory (
    warehouse_id bigint NOT NULL REFERENCES warehouses(id) ON DELETE RESTRICT,
    item_id bigint NOT NULL REFERENCES items(id) ON DELETE RESTRICT,
    quantity bigint NOT NULL CHECK (quantity >= 0),
    reserved bigint NOT NULL DEFAULT 0 CHECK (reserved >= 0 AND reserved <= quantity),
    PRIMARY KEY (warehouse_id, item_id)
);

COMMIT;
